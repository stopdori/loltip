import { korToEng } from "../utils/korToEng";

export type Champ = {
  id: string;
  ko: string;
  en: string;
  aliases?: { ko: string[]; en: string[] };
  search: string[];
};

const c = (
  id: string,
  ko: string,
  en: string,
  aliases: { ko: string[]; en: string[] } = { ko: [], en: [] }
): Champ => ({
  id,
  ko,
  en,
  aliases,
  search: [
    ko,
    en.toLowerCase(),
    id.toLowerCase(),
    korToEng(ko),
    ...aliases.ko,
    ...aliases.ko.map(korToEng),
    ...aliases.en,
  ],
});


